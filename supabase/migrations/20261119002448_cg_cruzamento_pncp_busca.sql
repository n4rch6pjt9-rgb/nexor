  where t.id ~ '^[0-9]+$' order by t.id on conflict (id) do update set nome = excluded.nome;

  insert into cg_pncp_busca(
    numero_controle_pncp, pncp_doc_id, document_type, item_url, site_url, fonte_plataforma_id,
    pncp_orgao_id, orgao_cnpj, orgao_nome, orgao_subrogado_id, orgao_subrogado_cnpj, orgao_subrogado_nome,
    pncp_unidade_id, unidade_codigo, unidade_nome, unidade_subrogada_id, unidade_subrogada_codigo, unidade_subrogada_nome,
    unidade_subrogada_municipio_id, unidade_subrogada_municipio_nome, unidade_subrogada_uf,
    esfera_id, poder_id, pncp_municipio_id, codigo_ibge, uf, modalidade_licitacao_id, modo_disputa_id, situacao_id, situacao_nome, status_pncp,
    data_publicacao_pncp, data_atualizacao_pncp, data_inicio_vigencia, data_fim_vigencia,
    data_inicio_recebimento_propostas, data_fim_recebimento_propostas,
    cancelado, tem_resultado, srp, valor_total_estimado, valor_total_homologado, indicador_orcamento_sigiloso,
    tem_ata_registro_preco, tem_contrato_empenho, tem_nfe_contrato, possui_nfe, possui_emenda_parlamentar,
    exigencia_conteudo_nacional, permite_adesao, tipo_margem_preferencia_id, tipo_margem_preferencia_nome,
    aplicabilidade_margem_preferencia, aplicabilidade_margem_preferencia_normal, aplicabilidade_margem_preferencia_adicional,
    incentivo_produtivo_basico, fonte_orcamentaria_ids, normativo_base_ids, amparo_legal_ids, criterio_julgamento_ids,
    link_sistema_origem, link_processo_eletronico, usuario_nome, raw, payload_hash)
  select distinct on (b.numero_controle_pncp)
    b.numero_controle_pncp, b.pncp_doc_id, b.document_type, b.item_url, b.site_url, f.id,
    b.pncp_orgao_id, b.orgao_cnpj, b.orgao_nome, b.orgao_subrogado_id, b.orgao_subrogado_cnpj, b.orgao_subrogado_nome,
    b.pncp_unidade_id, b.unidade_codigo, b.unidade_nome, b.unidade_subrogada_id, b.unidade_subrogada_codigo, b.unidade_subrogada_nome,
    b.unidade_subrogada_municipio_id, b.unidade_subrogada_municipio_nome, b.unidade_subrogada_uf,
    b.esfera_id, b.poder_id, b.pncp_municipio_id, b.codigo_ibge, b.uf, b.modalidade_licitacao_id, b.modo_disputa_id, b.situacao_id, b.situacao_nome, p_status,
    b.data_publicacao_pncp, b.data_atualizacao_pncp, b.data_inicio_vigencia, b.data_fim_vigencia,
    b.data_inicio_recebimento_propostas, b.data_fim_recebimento_propostas,
    b.cancelado, b.tem_resultado, b.srp, b.valor_total_estimado, b.valor_total_homologado, b.indicador_orcamento_sigiloso,
    b.tem_ata_registro_preco, b.tem_contrato_empenho, b.tem_nfe_contrato, b.possui_nfe, b.possui_emenda_parlamentar,
    b.exigencia_conteudo_nacional, b.permite_adesao, b.tipo_margem_preferencia_id, b.tipo_margem_preferencia_nome,
    b.aplicabilidade_margem_preferencia, b.aplicabilidade_margem_preferencia_normal, b.aplicabilidade_margem_preferencia_adicional,
    b.incentivo_produtivo_basico, b.fonte_ids, b.normativo_ids, b.amparo_ids, b.criterio_ids,
    b.link_sistema_origem, b.link_processo_eletronico, b.usuario_nome, b.raw, b.payload_hash
  from _cg_b b left join cg_fontes_plataformas f on f.dominio = b.site_url
  order by b.numero_controle_pncp, b.data_atualizacao_pncp desc nulls last
  on conflict (numero_controle_pncp) do update set
    pncp_doc_id = excluded.pncp_doc_id, document_type = excluded.document_type, item_url = excluded.item_url,
    site_url = excluded.site_url, fonte_plataforma_id = excluded.fonte_plataforma_id,
    pncp_orgao_id = excluded.pncp_orgao_id, orgao_cnpj = excluded.orgao_cnpj, orgao_nome = excluded.orgao_nome,
    orgao_subrogado_id = excluded.orgao_subrogado_id, orgao_subrogado_cnpj = excluded.orgao_subrogado_cnpj, orgao_subrogado_nome = excluded.orgao_subrogado_nome,
