create or replace function public.cg_ingest_pncp_busca(p jsonb, p_status text default null) returns integer
language plpgsql set search_path = public, extensions as $fn$
declare n integer := 0;
begin
  if p is null or jsonb_typeof(p) <> 'array' or jsonb_array_length(p) = 0 then return 0; end if;
  create temporary table _cg_b on commit drop as
  select
    r.id as pncp_doc_id, r.document_type, r.item_url, r.site_url, r.numero_controle_pncp,
    r.orgao_id as pncp_orgao_id, r.orgao_cnpj, r.orgao_nome,
    r.orgao_subrogado_id, r.orgao_subrogado_cnpj, r.orgao_subrogado_nome,
