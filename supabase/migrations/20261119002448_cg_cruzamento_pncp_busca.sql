alter table public.cg_status_contratacao add column if not exists grupo_pncp text;
update public.cg_status_contratacao set grupo_pncp = case codigo
  when 'a_receber' then 'recebendo_proposta' when 'recebendo_proposta' then 'recebendo_proposta'
  when 'em_julgamento' then 'propostas_encerradas' when 'propostas_encerradas' then 'propostas_encerradas'
  else 'encerradas' end
  where codigo in ('a_receber','recebendo_proposta','em_julgamento','propostas_encerradas','encerradas');
update public.cg_status_contratacao set observacao = 'No PNCP o filtro é um só: "A Receber/Recebendo Proposta" (valor recebendo_proposta). Aqui separado por data de abertura.' where codigo in ('a_receber','recebendo_proposta');
update public.cg_status_contratacao set observacao = 'No PNCP o filtro é um só: "Em Julgamento/Propostas Encerradas" (valor propostas_encerradas). Sem como separar os dois com os dados públicos.' where codigo in ('em_julgamento','propostas_encerradas');
update public.cg_status_contratacao set observacao = 'Valor encerradas do PNCP; no cálculo local: com resultado/homologação, revogada ou anulada.' where codigo = 'encerradas';

