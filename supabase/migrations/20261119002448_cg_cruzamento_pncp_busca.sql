    unidade_subrogada_id text, unidade_subrogada_codigo text, unidade_subrogada_nome text,
    unidade_subrogada_municipio_id text, unidade_subrogada_municipio_nome text, unidade_subrogada_uf text,
    esfera_id text, poder_id text, municipio_id text, codigo_ibge text, uf text,
    modalidade_licitacao_id text, modo_disputa_id text, situacao_id text, situacao_nome text,
    data_publicacao_pncp text, data_atualizacao_pncp text, data_inicio_vigencia text, data_fim_vigencia text,
    data_inicio_recebimento_propostas text, data_fim_recebimento_propostas text,
    cancelado boolean, tem_resultado boolean, srp boolean, valor_total_estimado numeric, valor_total_homologado numeric,
    indicador_orcamento_sigiloso boolean, tem_ata_registro_preco boolean, tem_contrato_empenho boolean, tem_nfe_contrato boolean,
    possui_nfe boolean, possui_emenda_parlamentar boolean, exigencia_conteudo_nacional boolean, permite_adesao boolean,
