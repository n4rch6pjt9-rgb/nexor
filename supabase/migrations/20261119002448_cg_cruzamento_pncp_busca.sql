    public.cg_ts(r.data_inicio_vigencia) as data_inicio_vigencia, public.cg_ts(r.data_fim_vigencia) as data_fim_vigencia,
    public.cg_ts(r.data_inicio_recebimento_propostas) as data_inicio_recebimento_propostas,
    public.cg_ts(r.data_fim_recebimento_propostas) as data_fim_recebimento_propostas,
    r.cancelado, r.tem_resultado, r.srp, r.valor_total_estimado, r.valor_total_homologado, r.indicador_orcamento_sigiloso,
    r.tem_ata_registro_preco, r.tem_contrato_empenho, r.tem_nfe_contrato, r.possui_nfe,
    r.possui_emenda_parlamentar, r.exigencia_conteudo_nacional, r.permite_adesao,
    r.tipo_margem_preferencia_id, r.tipo_margem_preferencia_nome,
    r.aplicabilidade_margem_preferencia, r.aplicabilidade_margem_preferencia_normal, r.aplicabilidade_margem_preferencia_adicional,
    r.incentivo_produtivo_basico,
    case when jsonb_typeof(r.fonte_orcamentaria_id) = 'array' then array(select jsonb_array_elements_text(r.fonte_orcamentaria_id)) end as fonte_ids,
    case when jsonb_typeof(r.fonte_orcamentaria_nome) = 'array' then array(select jsonb_array_elements_text(r.fonte_orcamentaria_nome)) end as fonte_nomes,
    case when jsonb_typeof(r.normativo_base_id) = 'array' then array(select jsonb_array_elements_text(r.normativo_base_id)) end as normativo_ids,
    case when jsonb_typeof(r.normativo_base_nome) = 'array' then array(select jsonb_array_elements_text(r.normativo_base_nome)) end as normativo_nomes,
    case when jsonb_typeof(r.amparo_legal_id) = 'array' then array(select jsonb_array_elements_text(r.amparo_legal_id)) end as amparo_ids,
    case when jsonb_typeof(r.criterio_julgamento_id) = 'array' then array(select jsonb_array_elements_text(r.criterio_julgamento_id)) end as criterio_ids,
    r.link_sistema_origem, r.link_processo_eletronico, r.usuario_nome,
    e as raw, md5(e::text) as payload_hash
  from jsonb_array_elements(p) as e,
  lateral jsonb_to_record(e) as r(
    id text, document_type text, item_url text, site_url text, numero_controle_pncp text,
    orgao_id text, orgao_cnpj text, orgao_nome text, orgao_subrogado_id text, orgao_subrogado_cnpj text, orgao_subrogado_nome text,
